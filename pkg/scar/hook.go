package scar

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const HookMarker = "# Generated by git-scars"

// InstallPreCommitHook installs a git pre-commit hook that runs git-scars check on staged files.
func InstallPreCommitHook(repoRoot string) error {
	gitDir := filepath.Join(repoRoot, ".git")
	if _, err := os.Stat(gitDir); os.IsNotExist(err) {
		return errors.New("cannot install hook: repository is not a git worktree (.git directory missing)")
	}

	hooksDir := filepath.Join(gitDir, "hooks")
	if err := os.MkdirAll(hooksDir, 0755); err != nil {
		return fmt.Errorf("failed creating hooks directory: %w", err)
	}

	hookPath := filepath.Join(hooksDir, "pre-commit")

	// If hook exists and was not generated by git-scars, append or warn
	if existing, err := os.ReadFile(hookPath); err == nil {
		if strings.Contains(string(existing), "git-scars") {
			return nil // already installed
		}
	}

	hookScript := fmt.Sprintf(`#!/usr/bin/env sh
%s
# Verify GitScars integrity and ensure no active scars anchored to modified files are stale

if command -v git-scars >/dev/null 2>&1; then
    git-scars check --diff HEAD
    EXIT_CODE=$?
    if [ $EXIT_CODE -eq 2 ]; then
        echo ""
        echo "[git-scars] WARNING: Active scar anchor modified. Run 'git-scars reaffirm <id>' to update baseline."
        echo ""
    elif [ $EXIT_CODE -ne 0 ]; then
        echo "[git-scars] Commit rejected: blocking findings detected (exit code $EXIT_CODE)."
        exit $EXIT_CODE
    fi
fi
`, HookMarker)

	if err := os.WriteFile(hookPath, []byte(hookScript), 0755); err != nil {
		return fmt.Errorf("failed writing pre-commit hook: %w", err)
	}

	return nil
}

// UninstallPreCommitHook removes the git-scars pre-commit hook.
func UninstallPreCommitHook(repoRoot string) error {
	hookPath := filepath.Join(repoRoot, ".git", "hooks", "pre-commit")
	data, err := os.ReadFile(hookPath)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}

	if strings.Contains(string(data), HookMarker) {
		return os.Remove(hookPath)
	}

	return nil
}

// IsHookInstalled checks if the git-scars pre-commit hook is present.
func IsHookInstalled(repoRoot string) bool {
	hookPath := filepath.Join(repoRoot, ".git", "hooks", "pre-commit")
	data, err := os.ReadFile(hookPath)
	if err != nil {
		return false
	}
	return strings.Contains(string(data), HookMarker)
}
