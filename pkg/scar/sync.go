package scar

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	SyncMarkerStart = "<!-- GIT-SCARS:START -->"
	SyncMarkerEnd   = "<!-- GIT-SCARS:END -->"
)

// DefaultSyncTargets specifies common AI coding agent instruction files.
var DefaultSyncTargets = []string{
	"AGENTS.md",
	"CLAUDE.md",
	".cursorrules",
	".windsurfrules",
}

// SyncResult records the outcome of syncing an individual instruction file.
type SyncResult struct {
	FilePath string `json:"file_path"`
	Updated  bool   `json:"updated"`
	Created  bool   `json:"created"`
	Action   string `json:"action"` // "updated", "created", "unchanged", "skipped"
}

// GenerateSyncBlock creates the managed markdown snippet of active scars.
func (s *Store) GenerateSyncBlock() (string, error) {
	summaries, err := s.ListScars()
	if err != nil {
		return "", err
	}

	var activeScars []*Scar
	for _, sum := range summaries {
		if sum.Scar.Lifecycle.State == LifecycleActive {
			activeScars = append(activeScars, sum.Scar)
		}
	}

	var sb strings.Builder
	sb.WriteString(SyncMarkerStart + "\n")
	sb.WriteString("<!-- Auto-generated by git-scars. Do not edit manually between markers. -->\n")
	sb.WriteString("## Repository Scars & Regression Guardrails\n\n")

	if len(activeScars) == 0 {
		sb.WriteString("No active scars recorded yet.\n\n")
	} else {
		sb.WriteString("| ID | Title | Anchors | Prevention Lesson | Verifier |\n")
		sb.WriteString("| :--- | :--- | :--- | :--- | :--- |\n")
		for _, sc := range activeScars {
			anchors := strings.Join(sc.Anchors.Files, ", ")
			if anchors == "" {
				anchors = strings.Join(sc.Anchors.Symbols, ", ")
			}
			if anchors == "" {
				anchors = "-"
			}
			verifier := strings.Join(sc.Verifier.Argv, " ")
			if verifier == "" {
				verifier = "-"
			}
			cleanTitle := strings.ReplaceAll(sc.Title, "|", "\\|")
			cleanLesson := strings.ReplaceAll(sc.Lesson, "|", "\\|")
			cleanLesson = strings.ReplaceAll(cleanLesson, "\n", " ")
			sb.WriteString(fmt.Sprintf("| `%s` | %s | `%s` | %s | `%s` |\n", sc.ID, cleanTitle, anchors, cleanLesson, verifier))
		}
		sb.WriteString("\n")
	}
	sb.WriteString(SyncMarkerEnd)
	return sb.String(), nil
}

// SyncInstructionFile updates or appends the managed block in a specific file.
func (s *Store) SyncInstructionFile(targetPath string) (*SyncResult, error) {
	block, err := s.GenerateSyncBlock()
	if err != nil {
		return nil, err
	}

	res := &SyncResult{FilePath: targetPath}
	data, err := os.ReadFile(targetPath)
	if os.IsNotExist(err) {
		if err := os.WriteFile(targetPath, []byte(block+"\n"), 0644); err != nil {
			return nil, err
		}
		res.Created = true
		res.Action = "created"
		return res, nil
	} else if err != nil {
		return nil, err
	}

	content := string(data)
	startIdx := strings.Index(content, SyncMarkerStart)
	endIdx := strings.Index(content, SyncMarkerEnd)

	var newContent string
	if startIdx != -1 && endIdx != -1 && endIdx >= startIdx {
		before := content[:startIdx]
		after := content[endIdx+len(SyncMarkerEnd):]
		newContent = before + block + after
	} else {
		trimmed := strings.TrimRight(content, "\n")
		newContent = trimmed + "\n\n" + block + "\n"
	}

	if newContent == content {
		res.Action = "unchanged"
		return res, nil
	}

	if err := os.WriteFile(targetPath, []byte(newContent), 0644); err != nil {
		return nil, err
	}
	res.Updated = true
	res.Action = "updated"
	return res, nil
}

// SyncExistingInstructions discovers and updates any existing instruction files in the repo root.
func (s *Store) SyncExistingInstructions(explicitTargets []string) ([]SyncResult, error) {
	var results []SyncResult

	if len(explicitTargets) > 0 {
		for _, target := range explicitTargets {
			fullPath := filepath.Join(s.RepoRoot, target)
			res, err := s.SyncInstructionFile(fullPath)
			if err != nil {
				return nil, fmt.Errorf("failed syncing %s: %w", target, err)
			}
			results = append(results, *res)
		}
		return results, nil
	}

	// Auto-discover existing targets
	for _, target := range DefaultSyncTargets {
		fullPath := filepath.Join(s.RepoRoot, target)
		if _, err := os.Stat(fullPath); err == nil {
			res, err := s.SyncInstructionFile(fullPath)
			if err != nil {
				return nil, fmt.Errorf("failed syncing %s: %w", target, err)
			}
			results = append(results, *res)
		}
	}

	return results, nil
}
